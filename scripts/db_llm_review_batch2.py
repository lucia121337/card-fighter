def main():
    con = sqlite3.connect(DB); cur = con.cursor()
    n = m = k = 0
    for idx, cat, tiers, memo in FILLS:
        cols = {}
        for i in range(10):
            cols[NG_TH[i]] = tiers[i][0] if i < len(tiers) else None
            cols[NG_CAP[i]] = tiers[i][1] if i < len(tiers) else None
        cols.update({'구간출처': 'llm-review', '검수상태': 'reviewing', '검수메모': memo})
        sets = ', '.join(f'"{c}"=?' for c in cols)
        n += cur.execute(f'UPDATE 혜택계산기 SET {sets} WHERE card_idx=? AND 혜택카테고리=?',
                         list(cols.values()) + [idx, cat]).rowcount
    for idx, cats, memo in NOCAP:
        for cat in cats:
            m += cur.execute("UPDATE 혜택계산기 SET 구간출처='llm-review-nocap', 검수상태='reviewing', 검수메모=? WHERE card_idx=? AND 혜택카테고리=?",
                             (memo, idx, cat)).rowcount
    for idx, cats, memo in COMPLEX:
        for cat in cats:
            k += cur.execute("UPDATE 혜택계산기 SET 구간출처='llm-review-complex', 검수상태='reviewing', 검수메모=? WHERE card_idx=? AND 혜택카테고리=?",
                             (memo, idx, cat)).rowcount
    con.commit()
    print(f'구간 채움 {n}행 / 무한도 확인 {m}행 / 복잡-사람판단 {k}행 (카드 30장)')


if __name__ == '__main__':
    main()
